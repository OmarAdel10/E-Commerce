/** The middleware's existing layout read supplies the store language; the browser keeps its <html lang>. */
export function continuationLanguage(code: unknown): "en" | "bn" {
  return checkoutLanguageBaseCode(code) === "bn" ? "bn" : "en";
}

export function continuationCopy(code: unknown): ContinuationCopy {
  return continuationLanguage(code) === "bn" ? BN : EN;
}
